// Regenerates server/scripts/sql/qa-migration-0110.sql: a paste-ready, single-transaction script for a database
// admin (Supabase SQL editor, role postgres) that applies migration 0110 and records its exact sha256 checksum
// in schema_migrations, so `scripts/migrate.mjs` finds nothing pending afterwards.
//
//   node scripts/generate-qa-migration-0110.mjs
//
// The checksum is computed exactly like scripts/migrate.mjs: sha256 of readFile(file, 'utf8'). The migration file
// is CRLF like its neighbours; do not change its line endings.
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const migrationsDir = join(here, '..', 'migrations');
const names = (await readdir(migrationsDir)).filter(name => /^\d{4}_[a-z0-9_]+\.sql$/.test(name)).sort();
const migrationName = names.find(name => name.startsWith('0110_'));
if (!migrationName) throw new Error('Migration 0110 not found.');
const prerequisite = names.filter(name => name < migrationName).at(-1);
const migrationSql = await readFile(join(migrationsDir, migrationName), 'utf8');
const checksum = createHash('sha256').update(migrationSql).digest('hex');
const body = migrationSql.replace(/^\s*(BEGIN|COMMIT)\s*;[ \t]*$/gim, '').trim().replace(/\r\n/g, '\n');
// plpgsql bodies legitimately contain a bare BEGIN; only statement-level transaction control is refused.
if (/^\s*(BEGIN\s*;|COMMIT\s*;|ROLLBACK\b|START\s+TRANSACTION\b|BEGIN\s+(WORK|TRANSACTION)\b)/im.test(body)) throw new Error('Migration 0110 contains transaction control beyond BEGIN/COMMIT; refusing to embed.');
const q = value => `'${String(value).replaceAll("'", "''")}'`;

const sql = `-- DLC migration ${migrationName} for the remote database (generated by server/scripts/generate-qa-migration-0110.mjs).
-- Run ONCE as a database admin (Supabase SQL editor, role postgres). One transaction, safe to re-run.
-- Adds operational_cut_profiles.day_end and the previous-cut helper, and updates the cut generation, meter capture,
-- preparation and closing functions so the academicLab22 branches can have a morning cut 06:00-14:00 and an
-- evening cut 14:00-22:00 (22:00-06:00 is not a cut). Existing cuts and profiles are not modified.
-- sha256 recorded in schema_migrations: ${checksum}
BEGIN;
SET LOCAL lock_timeout = '15s';
SELECT pg_advisory_xact_lock(hashtext('dlc-schema-migrations'));

DO $$ BEGIN
  IF to_regclass('public.schema_migrations') IS NULL OR NOT EXISTS (SELECT 1 FROM schema_migrations WHERE version = ${q(prerequisite)}) THEN
    RAISE EXCEPTION 'Schema is not at ${prerequisite}; apply migrations up to it first.';
  END IF;
END $$;

-- ===== ${migrationName} (BEGIN/COMMIT removed; the whole file is one transaction) =====
${body}
-- ===== end ${migrationName} =====

INSERT INTO schema_migrations (version, checksum) VALUES (${q(migrationName)}, ${q(checksum)})
ON CONFLICT (version) DO NOTHING;
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM schema_migrations WHERE version = ${q(migrationName)} AND checksum <> ${q(checksum)}) THEN
    RAISE WARNING '${migrationName} was already recorded with a different checksum; scripts/migrate.mjs will reject it until reconciled.';
  END IF;
END $$;

-- Result summary (last statement; shown by the SQL editor)
SELECT (SELECT checksum FROM schema_migrations WHERE version = ${q(migrationName)}) AS recorded_checksum,
       ${q(checksum)} AS expected_checksum,
       EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'operational_cut_profiles' AND column_name = 'day_end') AS day_end_column,
       to_regprocedure('previous_operational_cut(uuid)') IS NOT NULL AS previous_cut_function;

COMMIT;
`;
const target = join(here, 'sql', 'qa-migration-0110.sql');
await writeFile(target, sql, 'utf8');
process.stdout.write(`Wrote ${target}\nchecksum ${checksum}\n`);
